#!/usr/bin/python3
"""Forced SSH command. No shell evaluation, forwarding, arbitrary paths, or sudo."""
import os
from pathlib import Path
import re
import shlex
import sys
import subprocess
from deploy_static import Releases, validate_release, validate_slug


def parse_command(command, root=Path('/srv/personal-apps')):
    args = shlex.split(command)
    if args[:1] == ['deploy-static']:
        if len(args) == 4 and args[1] in ('activate', 'rollback'):
            validate_slug(args[2]); validate_release(args[3])
        elif len(args) == 3 and args[1] == 'status':
            validate_slug(args[2])
        elif len(args) == 5 and args[1] == 'rollback-if-current':
            validate_slug(args[2]); validate_release(args[3]); validate_release(args[4])
        elif args == ['deploy-static', 'cleanup']:
            pass
        else:
            raise ValueError('Unsupported deployment command')
        return ['/usr/local/lib/personal-apps/deploy_static.py', *args[1:]]
    # Exact rsync -rt --delete protocol generated by the documented client command.
    # No -L/-l/-H/-D, remote options, shell arguments, or arbitrary targets accepted.
    if not (len(args) == 6 and args[:2] == ['rsync', '--server']
            and args[2] == '-tre.iLsfxCIvu' and args[3:5] == ['--delete', '.']):
        raise ValueError('Only rsync -rt --delete uploads are accepted')
    destination = args[-1]
    match = re.fullmatch(re.escape(root.as_posix()) + r'/incoming/([^/]+)/([^/]+)/', destination)
    if not match:
        raise ValueError('Upload must target incoming/SLUG/RELEASE/')
    slug = validate_slug(match[1]); release = validate_release(match[2])
    Releases(root).safe_dir('incoming', slug, release)
    return ['/usr/bin/rsync', *args[1:]]


def main():
    args = parse_command(os.environ.get('SSH_ORIGINAL_COMMAND', ''))
    if args[0] == '/usr/bin/rsync':
        from storage_guard import require_storage
        manager = Releases()
        with manager.lock() as lock_handle:
            manager.cleanup_locked()
            require_storage(manager.root, 'upload')
            # Recheck destination after acquiring lock; no cleanup/activation overlaps upload.
            args = parse_command(os.environ.get('SSH_ORIGINAL_COMMAND', ''))
            destination = Path(args[-1])
            destination.mkdir(parents=True, exist_ok=True)
            os.umask(0o022)
            try:
                # Receiver retains the flock even if the SSH gateway is killed.
                # Also bound I/O inactivity independently of the parent timeout.
                result = subprocess.run([args[0], '--timeout=300', *args[1:]], timeout=300,
                                        pass_fds=(lock_handle.fileno(),))
            finally:
                os.utime(destination, None)
            sys.exit(result.returncode)
    os.umask(0o022)
    os.execv(args[0], args)


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, subprocess.TimeoutExpired) as error:
        print(f'Deployment command rejected: {error}', file=sys.stderr)
        sys.exit(1)
