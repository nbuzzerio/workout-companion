test('machine replacement permits empty and partial text, rejects invalid save, and retains P12 after reopening', async () => {
  const store = memoryStore()
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  const view = render(<App store={store} />)
  await waitFor(() => expect((screen.getByRole('button', { name: 'Start Workout' }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole('button', { name: 'Start Workout' }))
  const input = screen.getByLabelText('Leg Extension set 1 machine position') as HTMLInputElement
  fireEvent.focus(input)
  for (const value of ['', 'P']) {
    fireEvent.input(input, { target: { value } })
    expect(input.value).toBe(value)
  }
  fireEvent.blur(input)
  expect(input.getAttribute('aria-invalid')).toBe('true')
  fireEvent.click(screen.getByRole('button', { name: 'Save session' }))
  expect(store.save).not.toHaveBeenCalled()
  expect(screen.getByRole('alert').textContent).toContain('Enter a machine position')
  for (const value of ['P1', 'P12']) {
    fireEvent.input(input, { target: { value } })
    expect(input.value).toBe(value)
  }
  fireEvent.blur(input)
  expect(input.getAttribute('aria-invalid')).toBe('false')
  fireEvent.click(screen.getByRole('button', { name: 'Save session' }))
  await screen.findByText('Saved on this device.')
  view.unmount()
  render(<App store={store} />)
  fireEvent.click(await screen.findByRole('button', { name: /DEMO .*active/ }))
  expect((screen.getByLabelText('Leg Extension set 1 machine position') as HTMLInputElement).value).toBe('P12')
})

test('retry rereads a transiently inaccessible draft without remounting or losing edits', async () => {
  const store = memoryStore()
  const first = render(<App store={store} />)
  await waitFor(() => expect((screen.getByRole('button', { name: 'Start Workout' }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole('button', { name: 'Start Workout' }))
  fireEvent.change(screen.getByLabelText('DB Deadlift set 1 pounds'), { target: { value: '57' } })
  first.unmount()
  const raw = localStorage.getItem('workout-companion-draft-v1')
  const get = vi.spyOn(Storage.prototype, 'getItem').mockImplementationOnce(() => { throw new Error('transient read failure') })
  render(<App store={store} />)
  await waitFor(() => expect(store.list).toHaveBeenCalledTimes(2))
  expect((screen.getByRole('button', { name: 'Start Workout' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Retry storage / refresh history' }))
  await screen.findByText(/Recovered draft/)
  expect((screen.getByLabelText('DB Deadlift set 1 pounds') as HTMLInputElement).value).toBe('57')
  expect(screen.queryByRole('alert')).toBeNull()
  expect(get).toHaveBeenCalledTimes(2)
  expect(localStorage.getItem('workout-companion-draft-v1')).toBe(raw)
})

