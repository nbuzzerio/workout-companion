import { expect, test } from '@playwright/test'
import { appConfig } from '../../config/app.ts'

test('round-trips a completed workout on a narrow mobile screen', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.setViewportSize({ width: 320, height: 640 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto(appConfig.basePath)
  await expect(page.getByRole('button', { name: 'Import from Google Sheets' })).toBeEnabled()
  await page.getByLabel('Workout date').fill('2026-11-23')
  await page.getByRole('button', { name: 'Fri No plan' }).click()
  await page.getByRole('button', { name: 'Import from Google Sheets' }).click()
  const form = page.getByRole('region', { name: 'Google Sheets import' }).locator('form')
  await expect(form).toHaveCSS('color-scheme', 'dark')
  const paste = page.getByLabel('Paste Google Sheets cells')
  const row = ['CURRENT WEEK', '2026-11-18', 'Wed', 'Side plank', '35 sec per side', '45 sec', '4+', 'Tight', 'Sore', ''].join('\t')
  await paste.fill(row)
  await page.getByRole('button', { name: 'Preview import' }).click()
  await expect(page.getByText('Wed · 2026-11-18')).toBeVisible()
  await expect(page.getByText('Fri · 2026-11-23', { exact: true })).toBeVisible()
  await expect(page.getByText('35 sec per side', { exact: true })).toBeVisible()
  await expect(page.getByRole('radio', { name: 'Use Target values' })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Carry forward Coach Notes' })).not.toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.getByRole('button', { name: 'Review and edit exercises' }).click()
  await page.getByLabel('Side plank set 1 seconds per side').fill('40')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Confirm import' }).click()
  await expect(page.getByText('Workout plan imported for Fri · 2026-11-23.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Import from Google Sheets' })).toBeEnabled()
  await page.getByLabel('Workout date').fill('2026-11-23')
  await page.getByRole('button', { name: 'Fri Imported' }).click()
  await expect(page.getByText('40 sec per side', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Start Workout' }).click()
  await expect(page.getByRole('heading', { name: 'Side plank' })).toBeVisible()
  await expect(page.getByLabel('Side plank set 1 seconds per side')).toBeEmpty()
  await page.getByText('Exercise feedback', { exact: true }).click()
  await page.getByText('4+', { exact: true }).click()
  await page.getByText('Tight', { exact: true }).click()
  await page.getByLabel('Pain/Notes').fill('Sore after warmup')
  await page.getByLabel('Coach Notes').fill('Keep hips raised')
  await page.getByLabel('Side plank set 1 seconds per side').fill('38')
  await page.getByRole('button', { name: 'Review Workout' }).click()
  const loggedSet = page.getByRole('region', { name: 'Review workout' }).getByRole('listitem')
  await expect(loggedSet).toContainText('38 sec per side')
  await expect(loggedSet).toContainText('Planned 40 sec per side')
  page.once('dialog', dialog => void dialog.accept())
  await page.getByRole('button', { name: 'Finish Workout' }).click()
  await expect(page.getByRole('status')).toHaveText('Saved and completed on this device.')
  await page.reload()
  await page.getByLabel('Workout date').fill('2026-11-23')
  const completed = page.getByRole('button', { name: /2026-11-23.*completed/ })
  await completed.click()
  await expect(page.getByRole('region', { name: 'Workout finished' }).getByRole('listitem')).toContainText('38 sec per side')

  const exportWorkout = page.getByRole('button', { name: 'Export to Google Sheets' })
  const exportPreview = page.getByRole('region', { name: 'Google Sheets preview' })
  await exportWorkout.click()
  await expect(exportPreview.getByRole('row').nth(1).getByRole('cell')).toHaveText([
    'CURRENT WEEK', '2026-11-23', 'Fri', 'Side plank', '40 sec per side', '38 sec per side', '4+', '🟡 Tight', 'Sore after warmup', 'Keep hips raised',
  ])
  await exportPreview.getByRole('button', { name: 'Copy With Headers' }).click()
  await expect(exportPreview.getByRole('status')).toHaveText('Rows and headers copied.')
  await page.getByRole('button', { name: 'Back to plan' }).click()
  await page.getByRole('button', { name: 'Import from Google Sheets' }).click()
  await paste.press('ControlOrMeta+V')
  await expect(paste).toHaveValue(/Coach Notes\s+CURRENT WEEK.*Keep hips raised/su)
  await page.getByRole('button', { name: 'Preview import' }).click()
  const importPreview = page.getByRole('region', { name: 'Exercises and targets' })
  await expect(importPreview.getByText('40 sec per side', { exact: true })).toBeVisible()
  await expect(importPreview.getByText('Exercise feedback will start blank.')).toBeVisible()
  await importPreview.getByRole('radio', { name: 'Use Actual values' }).check()
  await importPreview.getByRole('checkbox', { name: 'Carry forward Coach Notes' }).check()
  await expect(importPreview.getByText('38 sec per side', { exact: true })).toBeVisible()
  await expect(importPreview.getByText('Keep hips raised')).toBeVisible()
  await expect(importPreview.getByText('Sore after warmup')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.getByRole('button', { name: 'Review and edit exercises' }).click()
  await expect(page.getByLabel('Side plank set 1 seconds per side')).toHaveValue('38')
  await expect(page.getByText('Keep hips raised')).toBeVisible()
  await page.getByRole('button', { name: 'Confirm import' }).click()
  await expect(completed).toHaveCount(1)
  await page.getByRole('button', { name: 'Start Workout' }).click()
  await expect(completed).toHaveCount(1)
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', '0')
  await expect(page.getByLabel('Side plank set 1 seconds per side')).toBeEmpty()
  await page.getByText('Exercise feedback', { exact: true }).click()
  await expect(page.getByLabel('Coach Notes')).toHaveValue('Keep hips raised')
  await expect(page.getByLabel('Pain/Notes')).toBeEmpty()
  await expect(page.getByRole('radio', { checked: true })).toHaveCount(0)
  await page.getByLabel('Side plank set 1 seconds per side').fill('41')
  await page.getByRole('button', { name: 'Review Workout' }).click()
  page.once('dialog', dialog => void dialog.accept())
  await page.getByRole('button', { name: 'Finish Workout' }).click()
  await expect(completed).toHaveCount(2)
  await exportWorkout.click()
  await expect(exportPreview.getByRole('row').nth(1).getByRole('cell')).toHaveText([
    'CURRENT WEEK', '2026-11-23', 'Fri', 'Side plank', '38 sec per side', '41 sec per side', '', '', '', 'Keep hips raised',
  ])
})
