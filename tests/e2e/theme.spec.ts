test('System uses the light palette on a light device', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto(appConfig.basePath)

  const root = page.locator('html')
  await expect(page.getByRole('combobox', { name: 'Appearance' })).toHaveValue('system')
  const start = page.getByRole('button', { name: 'Start Workout' })
  await expect(start).toBeEnabled()
  await expect(root).toHaveCSS('background-color', 'rgb(245, 245, 239)')
  await expect(root).toHaveCSS('color', 'rgb(32, 61, 48)')
  await expect(page.locator('.demo')).toHaveCSS('background-color', 'rgb(238, 240, 220)')
  await expect(start).toHaveCSS('background-color', 'rgb(37, 77, 59)')
  await expect(page.getByLabel('Workout date')).toHaveCSS('border-top-color', 'rgb(109, 129, 116)')

  await page.getByRole('button', { name: 'Edit recurring workout' }).click()
  const editor = page.getByRole('region', { name: 'Workout editor' })
  await expect(editor.locator('.exercise').first()).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(editor.getByRole('combobox').first()).toHaveCSS('background-color', 'rgb(255, 255, 255)')
})

test('System themes the runner and follows a live device change', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto(appConfig.basePath)

  const root = page.locator('html')
  await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')

  const selectedDay = page.getByRole('navigation', { name: 'Workout calendar' }).getByRole('button', { pressed: true })
  await selectedDay.hover()
  await expect(selectedDay).toHaveCSS('background-color', 'rgb(202, 236, 213)')
  await expect(selectedDay).toHaveCSS('color', 'rgb(23, 51, 39)')

  await page.getByRole('button', { name: 'Start Workout' }).click()
  const workout = page.getByRole('region', { name: 'DB Deadlift' })
  const pounds = page.getByLabel('DB Deadlift set 1 pounds')
  const reps = page.getByLabel('DB Deadlift set 1 reps')
  const progress = workout.getByRole('progressbar')
  await expect(workout).toHaveCSS('background-color', 'rgb(29, 43, 36)')
  await expect(progress).toHaveCSS('background-color', 'rgb(53, 72, 60)')
  await expect(pounds).toHaveCSS('background-color', 'rgb(34, 57, 45)')
  await expect(pounds).toHaveCSS('color', 'rgb(231, 239, 233)')

  await pounds.fill('-1')
  await workout.getByRole('button', { name: 'Next Set' }).click()
  const error = workout.getByRole('alert')
  await expect(error).toHaveCSS('color', 'rgb(255, 212, 204)')
  await expect(error).toHaveCSS('background-color', 'rgb(68, 42, 40)')

  await pounds.fill('51.5')
  await pounds.press('Tab')
  await expect(reps).toBeFocused()
  await expect(reps).toHaveCSS('outline-color', 'rgb(155, 202, 245)')
  await expect(reps).toHaveCSS('outline-style', 'solid')

  await page.getByText('Exercise feedback', { exact: true }).click()
  const notes = page.getByLabel('Pain/Notes')
  const mobility = page.getByRole('group', { name: 'Mobility' }).getByText('Tight', { exact: true })
  await expect(notes).toHaveCSS('background-color', 'rgb(34, 57, 45)')
  await expect(mobility).toHaveCSS('background-color', 'rgb(66, 54, 24)')

  await page.emulateMedia({ colorScheme: 'light' })
  await expect(root).toHaveCSS('background-color', 'rgb(245, 245, 239)')
  await expect(workout).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(notes).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(mobility).toHaveCSS('background-color', 'rgb(255, 241, 191)')
  await expect(pounds).toHaveValue('51.5')

  await page.getByRole('combobox', { name: 'Appearance' }).selectOption({ label: 'Dark' })
  await expect(workout).toHaveCSS('background-color', 'rgb(29, 43, 36)')
  await expect(pounds).toHaveValue('51.5')
})

test('explicit appearance survives reload and a browser restart', async ({ playwright, baseURL }, testInfo) => {
  const profile = testInfo.outputPath('appearance-profile')
  const launch = (colorScheme: 'dark' | 'light') => playwright.chromium.launchPersistentContext(profile, {
    baseURL, colorScheme, serviceWorkers: 'block', viewport: { width: 320, height: 720 },
  })
  const first = await launch('dark')
  try {
    const [page] = first.pages()
    await page.goto(appConfig.basePath)
    const appearance = page.getByRole('combobox', { name: 'Appearance' })
    const root = page.locator('html')
    await expect(appearance).toHaveValue('system')
    expect((await appearance.boundingBox())?.height).toBeGreaterThanOrEqual(44)
    await appearance.press('ArrowDown')
    await expect(appearance).toBeFocused()
    await expect(appearance).toHaveCSS('outline-style', 'solid')
    await expect(appearance).toHaveValue('light')
    await expect(root).toHaveCSS('background-color', 'rgb(245, 245, 239)')

    await page.reload()
    await expect(appearance).toHaveValue('light')
    await expect(root).toHaveCSS('color-scheme', 'light')
    await page.emulateMedia({ colorScheme: 'light' })
    await appearance.selectOption({ label: 'Dark' })
    await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')
    await page.emulateMedia({ colorScheme: 'dark' })
    await page.emulateMedia({ colorScheme: 'light' })
    await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')
  } finally {
    await first.close()
  }

  const second = await launch('light')
  try {
    const [page] = second.pages()
    const root = page.locator('html')
    const appearance = page.getByRole('combobox', { name: 'Appearance' })
    // With service workers blocked, the route prevents React from starting.
    await page.route('**/assets/*.js', route => route.abort())
    await page.goto(appConfig.basePath)
    await expect(page.locator('meta[name="color-scheme"]')).toHaveAttribute('content', 'dark')
    await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')
    await expect(appearance).toHaveCount(0)

    await page.unroute('**/assets/*.js')
    await page.reload()
    await expect(appearance).toHaveValue('dark')
    await appearance.selectOption({ label: 'System' })
    await expect(root).toHaveCSS('background-color', 'rgb(245, 245, 239)')
    await page.reload()
    await expect(appearance).toHaveValue('system')
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')
  } finally {
    await second.close()
  }
})

test('appearance falls back to System with invalid or unavailable storage', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto(appConfig.basePath)
  await page.evaluate(() => localStorage.setItem('workout-companion-appearance', 'invalid'))
  await page.reload()

  const appearance = page.getByRole('combobox', { name: 'Appearance' })
  const root = page.locator('html')
  await expect(appearance).toHaveValue('system')
  await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')

  await page.addInitScript(() => {
    const getItem = Storage.prototype.getItem
    const setItem = Storage.prototype.setItem
    Storage.prototype.getItem = function (key) {
      if (key === 'workout-companion-appearance') throw new Error('Storage denied')
      return getItem.call(this, key)
    }
    Storage.prototype.setItem = function (key, value) {
      if (key === 'workout-companion-appearance') throw new Error('Storage denied')
      setItem.call(this, key, value)
    }
  })
  await page.reload()
  await expect(appearance).toHaveValue('system')
  await expect(root).toHaveCSS('background-color', 'rgb(18, 26, 22)')
  await appearance.selectOption({ label: 'Light' })
  await expect(root).toHaveCSS('color-scheme', 'light')
  await expect(page.getByText('Appearance could not be saved on this device.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start Workout' })).toBeEnabled()
})

test('mobile import, confirmation, history and export update in place when switching themes', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto(appConfig.basePath)
  const appearance = page.getByRole('combobox', { name: 'Appearance' })
  const fitsViewport = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
  await appearance.selectOption('dark')
  const navigation = page.getByRole('navigation', { name: 'Workout calendar' })
  const friday = navigation.getByRole('button', { name: /Fri.*Rest day/ })
  await expect(friday).toBeEnabled()
  const mondayBounds = await navigation.getByRole('button', { name: /Mon.*DEMO Monday/ }).boundingBox()
  const fridayBounds = await friday.boundingBox()
  expect(fridayBounds!.y).toBeGreaterThan(mondayBounds!.y)
  expect(fridayBounds!.width).toBeGreaterThanOrEqual(44)

  await page.getByLabel('Workout date').fill('2026-11-23')
  await page.getByLabel('Workout weekday').selectOption('5')
  await page.getByRole('button', { name: 'Import from Google Sheets' }).click()
  const importForm = page.getByRole('region', { name: 'Google Sheets import' }).locator('form')
  const paste = page.getByLabel('Paste Google Sheets cells')
  await expect(importForm).toHaveCSS('background-color', 'rgb(29, 43, 36)')
  await expect(paste).toHaveCSS('background-color', 'rgb(34, 57, 45)')
  await page.getByRole('button', { name: 'Preview import' }).click()
  await expect(paste).toHaveAttribute('aria-invalid', 'true')
  await expect(paste).toHaveCSS('border-top-color', 'rgb(255, 212, 204)')
  const row = ['CURRENT WEEK', '2026-11-18', 'Wed', 'Side plank', '35 sec per side', '', '', '', '', ''].join('\t')
  await paste.fill(row)
  await page.getByRole('button', { name: 'Preview import' }).click()
  const notice = page.getByText(/The spreadsheet date and day differ/)
  await expect(notice).toHaveCSS('background-color', 'rgb(66, 54, 24)')
  await appearance.selectOption('light')
  await expect(paste).toHaveValue(row)
  await expect(importForm).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(notice).toHaveCSS('background-color', 'rgb(255, 241, 191)')
  expect(await fitsViewport()).toBe(true)

  await page.getByRole('button', { name: 'Review and edit exercises' }).click()
  const editor = page.getByRole('region', { name: 'Workout editor' })
  const target = editor.getByRole('combobox', { name: 'Side plank set 1 target type' })
  await appearance.selectOption('dark')
  await expect(target).toHaveCSS('background-color', 'rgb(34, 57, 45)')
  await expect(target).toHaveCSS('font-size', '16px')
  expect(await fitsViewport()).toBe(true)
  await page.getByRole('button', { name: 'Confirm import' }).click()
  await page.getByRole('button', { name: 'Start Workout' }).click()
  const previous = page.getByRole('button', { name: 'Previous Set' })
  await expect(previous).toBeDisabled()
  await expect(previous).toHaveCSS('color', 'rgb(180, 198, 186)')
  await page.getByLabel('Side plank set 1 seconds per side').fill('38')
  await page.getByRole('button', { name: 'Review Workout' }).click()

  const finish = page.getByRole('button', { name: 'Finish Workout' })
  const dialog = page.getByRole('dialog', { name: 'Finish and save this workout?' })
  await finish.click()
  await expect(dialog).toHaveCSS('background-color', 'rgb(29, 43, 36)')
  await expect(dialog).toHaveCSS('color', 'rgb(231, 239, 233)')
  expect(await dialog.evaluate(node => getComputedStyle(node, '::backdrop').backgroundColor)).toBe('rgba(0, 0, 0, 0.6)')
  await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(finish).toBeFocused()
  await expect(page.getByText('No saved sessions for this date.')).toBeVisible()
  await appearance.selectOption('light')
  await finish.click()
  await expect(dialog).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(dialog).toHaveCSS('color', 'rgb(32, 61, 48)')
  expect(await dialog.evaluate(node => getComputedStyle(node, '::backdrop').backgroundColor)).toBe('rgba(20, 38, 27, 0.4)')
  await dialog.getByRole('button', { name: 'OK' }).click()

  const history = page.getByRole('complementary', { name: 'Saved sessions' })
  const saved = history.getByRole('button', { name: /2026-11-23.*completed/ })
  await expect(saved).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.getByRole('button', { name: 'Back to plan' }).click()
  await saved.click()
  await page.getByRole('button', { name: 'Export to Google Sheets' }).click()
  const exportPreview = page.getByRole('region', { name: 'Google Sheets preview' })
  const column = exportPreview.getByRole('columnheader', { name: 'Actual' })
  await expect(column).toHaveCSS('background-color', 'rgb(230, 238, 231)')
  await appearance.selectOption('dark')
  await expect(saved).toHaveCSS('background-color', 'rgb(34, 57, 45)')
  await expect(column).toHaveCSS('background-color', 'rgb(56, 91, 73)')
  await expect(exportPreview.getByRole('cell', { name: '38 sec per side' })).toBeVisible()
  expect(await fitsViewport()).toBe(true)
})
